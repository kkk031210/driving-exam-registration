def generate(filename=None):
    """生成格式化的题库文本文件"""
    # 使用脚本所在目录作为基准，确保无论在哪运行都能生成到正确位置
    if filename is None:
        script_dir = os.path.dirname(os.path.abspath(__file__))
        filename = os.path.join(script_dir, "data", "questions.txt")
    
    # 确保 data 目录存在
    os.makedirs(os.path.dirname(filename), exist_ok=True)
    
    with open(filename, "w", encoding="utf-8") as f:
        # 写入文件头说明
        f.write("# 驾考报名管理系统题库文件\n")
        f.write("# 格式: 编号|科目|题型|题目|选项A|选项B|选项C|选项D|答案|解析\n")
        f.write("# 科目: 1=科目一, 4=科目四\n")
        f.write("# 题型: 1=单选, 2=判断\n")
        f.write("# ============================================\n")
        
        for q in QUESTIONS:
            id_, subject, qtype, content, opt_a, opt_b, opt_c, opt_d, answer, explanation = q
            # 用 | 作为分隔符，将内容中的 | 替换为全角｜避免冲突
            content = content.replace("|", "｜")
            opt_a = opt_a.replace("|", "｜")
            opt_b = opt_b.replace("|", "｜")
            opt_c = opt_c.replace("|", "｜")
            opt_d = opt_d.replace("|", "｜")
            answer = answer.replace("|", "｜")
            explanation = explanation.replace("|", "｜")
            
            line = f"{id_}|{subject}|{qtype}|{content}|{opt_a}|{opt_b}|{opt_c}|{opt_d}|{answer}|{explanation}\n"
            f.write(line)
    
    print(f"[成功] 已生成题库文件: {filename}")
    print(f"[统计] 共 {len(QUESTIONS)} 道题目")
    subject1_count = sum(1 for q in QUESTIONS if q[1] == 1)
    subject4_count = sum(1 for q in QUESTIONS if q[1] == 4)
    print(f"       科目一: {subject1_count} 题")
    print(f"       科目四: {subject4_count} 题")

if __name__ == "__main__":
    generate()
